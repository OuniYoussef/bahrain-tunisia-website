import { readFileSync, writeFileSync } from 'node:fs';
import { sampleStories } from '../src/features/vault/api/samples.ts';
const quote = (value) => value === null ? 'null' : typeof value === 'string' ? `'${value.replaceAll("'", "''")}'` : String(value);
const columns = ['id', 'title', 'country', 'category', 'locale', 'sample_image_id', 'body', 'author_name', 'status', 'is_sample', 'approved_at'];
for (const story of sampleStories) {
  const words = story.body.split(/\s+/).length;
  if (words < 60 || words > 90) throw new Error(`${story.id}: ${words} words`);
}
const sql = '-- Generated by node scripts/seed-samples.mjs from samples.ts. Do not seed production.\n' +
  `insert into public.stories (${columns.join(', ')}) values\n` +
  sampleStories.map((story) => `(${columns.map((column) => quote(story[column])).join(', ')})`).join(',\n') +
  '\non conflict (id) do nothing;\n';
if (process.argv.includes('--check')) {
  if (readFileSync('supabase/seed.sql', 'utf8') !== sql) throw new Error('Seed and mock samples differ');
} else writeFileSync('supabase/seed.sql', sql);
